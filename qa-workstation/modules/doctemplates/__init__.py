"""Doc & PPT Templates — a file holder for document and presentation
templates (.docx / .pptx / .xlsx / .pdf / .md …).

Files live flat in data/templates/ (gitignored); notes and tags per
file in data/templates/index.json. The folder is scanned on every
view, so a template generated by the assistant and written straight
into data/templates/ shows up without an upload.
"""
import json
import re
import time
from pathlib import Path

from flask import (Blueprint, render_template, request, redirect, url_for,
                   jsonify, send_from_directory, abort)

bp = Blueprint("doctemplates", __name__, url_prefix="/templates")

MODULE_INFO = {
    "name": "Doc & PPT Templates",
    "url": "/templates",
    "desc": "File holder for Word, PowerPoint and other templates — upload, tag, download; generated templates land here too.",
    "icon": "📑",
}

DATA_DIR = Path(__file__).resolve().parents[2] / "data" / "templates"
META_FILE = DATA_DIR / "index.json"

KINDS = {
    "ppt": {"label": "PowerPoint", "icon": "📊", "ext": (".pptx", ".ppt", ".potx", ".pptm")},
    "doc": {"label": "Word / document", "icon": "📝", "ext": (".docx", ".doc", ".dotx", ".docm", ".rtf", ".odt")},
    "sheet": {"label": "Excel", "icon": "📗", "ext": (".xlsx", ".xls", ".xltx", ".xlsm", ".csv")},
    "pdf": {"label": "PDF", "icon": "📄", "ext": (".pdf",)},
    "text": {"label": "Text / Markdown", "icon": "🗒", "ext": (".md", ".txt", ".html", ".json")},
    "other": {"label": "Other", "icon": "📎", "ext": ()},
}
ALLOWED = {e for k in KINDS.values() for e in k["ext"]} | {".zip", ".png", ".jpg", ".jpeg", ".svg"}


def kind_of(name):
    ext = Path(name).suffix.lower()
    for key, k in KINDS.items():
        if ext in k["ext"]:
            return key
    return "other"


def safe_name(name):
    name = Path(name).name
    name = re.sub(r"[\\/:*?\"<>|\x00-\x1f]", "_", name).strip(" .")
    return name or "file"


def load_meta():
    if META_FILE.exists():
        try:
            return json.loads(META_FILE.read_text(encoding="utf-8"))
        except json.JSONDecodeError:
            pass
    return {}


def save_meta(meta):
    DATA_DIR.mkdir(parents=True, exist_ok=True)
    META_FILE.write_text(json.dumps(meta, indent=1, ensure_ascii=False), encoding="utf-8")


def list_files():
    DATA_DIR.mkdir(parents=True, exist_ok=True)
    meta = load_meta()
    out = []
    for p in DATA_DIR.iterdir():
        if not p.is_file() or p.name == META_FILE.name or p.name.startswith("."):
            continue
        m = meta.get(p.name, {})
        st = p.stat()
        k = kind_of(p.name)
        out.append({
            "name": p.name, "kind": k, "kind_label": KINDS[k]["label"], "icon": KINDS[k]["icon"],
            "size": st.st_size, "size_kb": f"{st.st_size / 1024:.0f} KB" if st.st_size < 1048576 else f"{st.st_size / 1048576:.1f} MB",
            "modified": time.strftime("%Y-%m-%d %H:%M", time.localtime(st.st_mtime)),
            "notes": m.get("notes", ""), "tags": m.get("tags", []), "source": m.get("source", ""),
        })
    out.sort(key=lambda f: f["modified"], reverse=True)
    return out


def unique_name(name):
    p = DATA_DIR / name
    if not p.exists():
        return name
    stem, ext = Path(name).stem, Path(name).suffix
    n = 2
    while (DATA_DIR / f"{stem} ({n}){ext}").exists():
        n += 1
    return f"{stem} ({n}){ext}"


def store_file(filename, data, notes="", tags=None, source="upload"):
    """Save bytes as a template (used by the upload route and by any
    module / assistant that generates a template)."""
    DATA_DIR.mkdir(parents=True, exist_ok=True)
    name = unique_name(safe_name(filename))
    (DATA_DIR / name).write_bytes(data)
    meta = load_meta()
    meta[name] = {"notes": notes, "tags": tags or [], "source": source,
                  "added": time.strftime("%Y-%m-%d %H:%M")}
    save_meta(meta)
    return name


@bp.route("/")
def index():
    files = list_files()
    counts = {k: sum(1 for f in files if f["kind"] == k) for k in KINDS}
    return render_template("doctemplates/index.html", files=files, kinds=KINDS, counts=counts,
                           folder=str(DATA_DIR))


@bp.route("/upload", methods=["POST"])
def upload():
    saved, skipped = [], []
    tags = [t.strip() for t in request.form.get("tags", "").split(",") if t.strip()]
    for f in request.files.getlist("files"):
        if not f.filename:
            continue
        if Path(f.filename).suffix.lower() not in ALLOWED:
            skipped.append(f.filename)
            continue
        saved.append(store_file(f.filename, f.read(), notes=request.form.get("notes", ""), tags=tags))
    if request.accept_mimetypes.best == "application/json" or request.args.get("json"):
        return jsonify({"ok": True, "saved": saved, "skipped": skipped, "files": list_files()})
    return redirect(url_for("doctemplates.index"))


@bp.route("/file/<path:name>")
def download(name):
    name = safe_name(name)
    if not (DATA_DIR / name).is_file():
        abort(404)
    return send_from_directory(DATA_DIR, name, as_attachment=request.args.get("dl") == "1")


@bp.route("/api/files")
def api_files():
    return jsonify({"ok": True, "files": list_files()})


@bp.route("/api/file/<path:name>", methods=["POST", "DELETE"])
def api_file(name):
    name = safe_name(name)
    path = DATA_DIR / name
    if not path.is_file():
        return jsonify({"ok": False, "error": "not found"}), 404
    meta = load_meta()
    if request.method == "DELETE":
        path.unlink()
        meta.pop(name, None)
        save_meta(meta)
        return jsonify({"ok": True, "files": list_files()})
    data = request.get_json(force=True) or {}
    entry = meta.get(name, {})
    if "notes" in data:
        entry["notes"] = str(data["notes"])
    if "tags" in data:
        tags = data["tags"] if isinstance(data["tags"], list) else str(data["tags"]).split(",")
        entry["tags"] = [str(t).strip() for t in tags if str(t).strip()]
    new_name = safe_name(data.get("rename", "")) if data.get("rename") else ""
    if new_name and new_name != name:
        if not Path(new_name).suffix:
            new_name += path.suffix
        if (DATA_DIR / new_name).exists():
            return jsonify({"ok": False, "error": f"{new_name} already exists"}), 409
        path.rename(DATA_DIR / new_name)
        meta.pop(name, None)
        name = new_name
    meta[name] = entry
    save_meta(meta)
    return jsonify({"ok": True, "name": name, "files": list_files()})
